const chineseNames = new Map(READING_BOOKS.flatMap(([english, chinese]) => [[english.toLowerCase(), chinese], [chinese, chinese]]));
/** Keep custom titles intact; callers validate source names before making paths. */
export function chineseBookName(name: string): string {
  const trimmed = name.trim();
  return chineseNames.get(trimmed.toLowerCase()) ?? trimmed;
}
